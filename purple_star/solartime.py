def equation_of_time(year, month, day):
    """均时差（分钟）。"""
    import datetime

    n = datetime.date(year, month, day).timetuple().tm_yday
    b = 360.0 * (n - 81) / 365.0
    rad = math.radians
    return 9.87 * math.sin(rad(2 * b)) - 7.53 * math.cos(rad(b)) - 1.5 * math.sin(rad(b))


def true_solar(hour, minute, year, month, day, lon=120.0):
    """返回真太阳时的 (hour, minute)，可能跨日（hour 可 <0 或 >=24）。"""
    total = hour * 60 + minute
    total += (lon - 120.0) * 4.0
    total += equation_of_time(year, month, day)
    total = total % (24 * 60)
    return int(total // 60), int(total % 60)


def hour_index_true(hour, minute):
    """真太阳时的时辰序号（0=子 ... 11=亥）。"""
    if hour >= 23 or hour < 1:
        return 0
    return (hour + 1) // 2 % 12
